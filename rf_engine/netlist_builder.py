"""
CircuitRF Netlist (.cnl) Generator and Formatter.
Constructs syntax-verified .cnl documents for CircuitRF simulations.
"""

from typing import Dict, Any, List

class CircuitRFNetlistBuilder:
    def __init__(self, title: str = "RF Design Circuit"):
        self.title = title
        self.ports: List[str] = []
        self.components: List[str] = []
        self.analyses: List[str] = []
        self.tuning_goals: List[str] = []

    def add_port(self, name: str, net_pos: str, net_neg: str = "0", num: int = 1, z0: float = 50.0):
        self.ports.append(f"Port:{name} {net_pos} {net_neg} Num={num} Z={z0} Ohm")

    def add_resistor(self, name: str, net1: str, net2: str, value_ohm: float):
        self.components.append(f"R:{name} {net1} {net2} R={value_ohm:.3f} Ohm")

    def add_inductor(self, name: str, net1: str, net2: str, value_nh: float):
        self.components.append(f"L:{name} {net1} {net2} L={value_nh:.4f} nH")

    def add_capacitor(self, name: str, net1: str, net2: str, value_pf: float):
        self.components.append(f"C:{name} {net1} {net2} C={value_pf:.4f} pF")

    def add_sparam_analysis(
        self,
        name: str = "SP1",
        start_ghz: float = 1.0,
        stop_ghz: float = 10.0,
        npts: int = 101
    ):
        self.analyses.append(
            f"analysis {name} type=sparam start={start_ghz:.4f} stop={stop_ghz:.4f} npts={npts} Unit=GHz"
        )

    def add_optimization_goal(self, goal_name: str, expression: str, analysis: str, condition: str, target: float):
        self.tuning_goals.append(f"goal {goal_name} = {expression} analysis={analysis} {condition} {target}")

    def build(self) -> str:
        lines = [
            f"# ============================================================",
            f"# CircuitRF Netlist: {self.title}",
            f"# Generated by M365 Copilot RF Expert Agent",
            f"# ============================================================",
            ""
        ]
        if self.ports:
            lines.append("# --- Ports ---")
            lines.extend(self.ports)
            lines.append("")

        if self.components:
            lines.append("# --- Components ---")
            lines.extend(self.components)
            lines.append("")

        if self.analyses:
            lines.append("# --- Simulation Directives ---")
            lines.extend(self.analyses)
            lines.append("")

        if self.tuning_goals:
            lines.append("# --- Optimization Goals ---")
            lines.extend(self.tuning_goals)
            lines.append("")

        return "\n".join(lines)

def build_attenuator_pad_cnl(
    pad_name: str,
    r_series: float,
    r_shunt1: float,
    r_shunt2: float,
    start_ghz: float = 1.0,
    stop_ghz: float = 18.0,
    npts: int = 101
) -> str:
    """Builds a 2-port matched Pi-pad attenuator netlist."""
    builder = CircuitRFNetlistBuilder(title=f"Pi-Pad Attenuator: {pad_name}")
    builder.add_port("P1", "in", "0", num=1, z0=50.0)
    builder.add_port("P2", "out", "0", num=2, z0=50.0)
    builder.add_resistor("R_sh1", "in", "0", r_shunt1)
    builder.add_resistor("R_ser", "in", "out", r_series)
    builder.add_resistor("R_sh2", "out", "0", r_shunt2)
    builder.add_sparam_analysis("SP1", start_ghz=start_ghz, stop_ghz=stop_ghz, npts=npts)
    return builder.build()

def build_bandpass_filter_cnl(
    filter_name: str,
    f0_ghz: float,
    bw_ghz: float,
    order: int = 3,
    start_ghz: float = None,
    stop_ghz: float = None,
    npts: int = 201
) -> str:
    """
    Synthesizes coupled resonator bandpass filter netlist in .cnl format.
    """
    if start_ghz is None:
        start_ghz = max(0.1, f0_ghz - 2.0 * bw_ghz)
    if stop_ghz is None:
        stop_ghz = f0_ghz + 2.0 * bw_ghz

    builder = CircuitRFNetlistBuilder(title=f"Bandpass Filter ({order}th Order): {filter_name}")
    builder.add_port("P1", "in", "0", num=1, z0=50.0)
    builder.add_port("P2", "out", "0", num=2, z0=50.0)

    # Simplified coupled LC ladder model
    omega0 = 2.0 * 3.14159265 * (f0_ghz * 1e9)
    z0 = 50.0
    l_val_nh = (z0 / omega0) * 1e9
    c_val_pf = (1.0 / (omega0 * z0)) * 1e12

    builder.add_inductor("L1", "in", "n1", l_val_nh)
    builder.add_capacitor("C1", "n1", "0", c_val_pf)
    builder.add_capacitor("Cc12", "n1", "n2", c_val_pf * 0.15)
    builder.add_inductor("L2", "n2", "0", l_val_nh)
    builder.add_capacitor("C2", "n2", "0", c_val_pf)
    builder.add_capacitor("Cc23", "n2", "out", c_val_pf * 0.15)
    builder.add_inductor("L3", "out", "0", l_val_nh)

    builder.add_sparam_analysis("SP1", start_ghz=start_ghz, stop_ghz=stop_ghz, npts=npts)
    return builder.build()
